  var SPORTS_ICON = { gb: 'fb', ch: 'bk', pk: 'hk', dm: 'bs', gf: 'gf' };
  NP.iconKey = function (it) {
    if (!it) return null;
    if (it.kind === 'grail') return 'np';
    if (it.kind === 'merch') return I[it.id] ? it.id : null;
    if (it.kind === 'lot') return null;
    var id = it.id || '';
    if (id === 'mf1' || id === 'mf2' || id === 'mf3') return 'mf';
    if (I[id]) return id;
    var sp = SPORTS_ICON[id.slice(0, 2)];
    return sp || null;
  };

  NP.drawIcon = function (ctx, key, x, y, k) {
    var ic = I[key]; if (!ic) return;
    k = k || 1;
    ctx.fillStyle = ic.bg; ctx.fillRect(x, y, 16 * k, 16 * k);
    for (var r = 0; r < 16; r++) {
      var row = ic.px[r] || '';
      for (var c = 0; c < 16; c++) {
        var col = PAL[row.charAt(c)];
        if (col) { ctx.fillStyle = col; ctx.fillRect(x + c * k, y + r * k, k, k); }
      }
    }
  };

  // the picture for one item, with sequel numbers and the party hat where they belong
  NP.drawItemIcon = function (ctx, it, x, y, k) {
    var key = NP.iconKey(it);
    if (!key) return false;
    NP.drawIcon(ctx, key, x, y, k);
    if (it.id === 'mf3') { // party hat on the ferret
      var P = function (px, py, c) { ctx.fillStyle = c; ctx.fillRect(x + px * k, y + py * k, k, k); };
      P(2, 4, PAL.p); P(1, 5, PAL.p); P(2, 5, PAL.y); P(3, 5, PAL.p); P(1, 6, PAL.y); P(2, 6, PAL.p); P(3, 6, PAL.y); P(2, 3, PAL.W);
    }
    if (it.id === 'mf2' || it.id === 'mf3') {
      var d = it.id.charAt(2);
      NP.pixelText(ctx, d, x + 7 * k, y + 2 * k, k, PAL.k);
      NP.pixelText(ctx, d, x + 6 * k, y + 1 * k, k, PAL.c);
    }
    return true;
  };
